'use strict';
// Hashes written by bcrypt 5.1.1 (the version before the upgrade) must still verify
// with the installed bcrypt. Fixtures are hashes of public test-only passwords
// (the demo seed password and the local-dev admin password), never real ones.
// Usage: node tests/bcrypt-compat-test.js
const path = require('path');
const { APP_DIR, reporter } = require('./lib');

const bcrypt = require(path.join(APP_DIR, 'node_modules', 'bcrypt'));
const version = require(path.join(APP_DIR, 'node_modules', 'bcrypt', 'package.json')).version;
const rep = reporter();
const { check } = rep;

const FIXTURES = [
  // [label, password, hash generated by bcrypt 5.1.1]
  ['cost 10 ($2b$, seed-demo.js)', 'demo1234', '$2b$10$d01v5u3VAgvaF9iBRiW4wOoKCglEVjO1OZJbqBB58Yawci1ClbLLe'],
  ['cost 12 ($2b$, server.js)', 'localadmin123', '$2b$12$5Q2bydBXwQCB.Tnj0CA4Xu5mcCsP/y.WKKWA8wmTU46ksPtN2C1em'],
];

(async () => {
  console.log(`bcrypt ${version}`);
  for (const [label, pw, hash] of FIXTURES) {
    check(`${label}: correct password verifies`, await bcrypt.compare(pw, hash));
    check(`${label}: wrong password rejected`, !(await bcrypt.compare(pw + 'x', hash)));
    check(`${label}: $2a$ variant verifies`, await bcrypt.compare(pw, hash.replace(/^\$2b\$/, '$2a$')));
  }
  const fresh = await bcrypt.hash('new-password-1', 12);
  check('new hashes use $2b$ cost 12 and verify', fresh.startsWith('$2b$12$') && (await bcrypt.compare('new-password-1', fresh)));
  console.log(rep.failures ? `\n${rep.failures} bcrypt check(s) FAILED` : '\nall bcrypt checks passed');
  process.exit(rep.failures ? 1 : 0);
})();
